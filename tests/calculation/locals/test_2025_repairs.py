@pytest.mark.parametrize("income,expected", [("15649", "0"), ("15650", "291.20"), ("15651", "291.23")])
def test_baltimore_local_poverty_credit_strict_boundary(income, expected):
    # 2025 booklet Instruction16: fixed3350 deduction plus3200 exemption.
    # EIC deliberately zero to isolate the poverty-credit boundary.
    base = D(income) - 6550
    result = LocalCalculator().calculate(local_input("US-MD-BAL", wages=income,
        income=income, state_base=str(base)))
    assert result.total_tax == D(expected)


def test_baltimore_local_eic_is_separate_nonrefundable_credit():
    data = local_input("US-MD-BAL", wages="18000", income="18000", state_base="11450")
    data.federal_earned_income_credit = D(100)  # Known fixture federal amount.
    result = LocalCalculator().calculate(data)
    assert result.tax_before_credits == D("366.40")
    assert result.nonrefundable_credits == D(32)  # 19B: federal EIC ×(.032×10).
    assert result.total_tax == D("334.40")
    assert result.refundable_credits == 0
