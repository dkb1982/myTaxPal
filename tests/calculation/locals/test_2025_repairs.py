def test_yonkers_uses_instructed_base_not_refund_reduced_state_total():
    data = local_input("US-NY-YNK", yonkers_surcharge_base=D("20002.10"))
    data.state_tax = D("19002.10")
    assert LocalCalculator().calculate(data).total_tax == D("3350.35")


def test_nyc_gross_and_refundable_credit_basis():
    result = LocalCalculator().calculate(local_input("US-NY-NYC"))
    assert result.tax_before_credits == D("3441.09")
    assert result.refundable_credits == D("266.40")
    assert result.total_tax == D("3174.69")
    zero = LocalCalculator().calculate(local_input("US-NY-NYC", wages="0", income="0", state_base="0"))
    assert zero.total_tax == D(-63)


@pytest.mark.parametrize("agi,fixed,rate_credit", [
    ("250000", "63", "545.40"), ("250001", "0", "545.40"),
    ("500000", "0", "1115.40"), ("500001", "0", "0"),
])
def test_nyc_credit_income_ceiling_not_taxable_income(agi, fixed, rate_credit):
    data = local_input("US-NY-NYC", wages=agi, income=agi, state_base=str(D(agi)-8000))
    result = LocalCalculator().calculate(data)
    amounts = {c.credit_id: c.amount_applied for c in result.credits}
    assert amounts["NYC-SCHOOL-FIXED"] == D(fixed)
    assert amounts["NYC-SCHOOL-RATE"] == D(rate_credit)


