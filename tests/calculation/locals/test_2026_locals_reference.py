"""2026 resident local reference values (single, age 40, lives and works in city).

Expectations are hand calculations from the sources in rules/locals/2026/*.yaml;
they are not generated by the calculator. State-derived inputs (NY taxable
income / tax for Yonkers, MD and IN state taxable income) are hand-computed
from 2026 state law: NY $8,000 standard deduction and Tax Law 601 schedule;
MD $3,400 standard deduction and $3,200 exemption (none above $150,000 FAGI);
IN $1,000 exemption.

Scenarios: wages $40,000 / $100,000 / $250,000 and "mixed" = $80,000 wages +
$5,000 qualified dividends + $10,000 long-term gains (FAGI $95,000).
"""
from decimal import Decimal as D

import pytest

from tax_estimator.calculation.locals.calculator import LocalCalculator
from tax_estimator.calculation.locals.models import LocalTaxInput
from tax_estimator.calculation.locals.policies_2026 import (
    LOCAL_PENDING_2026,
    LOCAL_POLICIES_2026,
)

ADVERTISED = {"US-NY-NYC", "US-NY-YNK", "US-PA-PHL", "US-MI-DET", "US-OH-CLE",
              "US-OH-CIN", "US-OH-CMH", "US-MD-BAL", "US-IN-IND", "US-AL-BHM",
              "US-KY-LOU"}
SCENARIOS = {  # name -> (wages, qualified dividends, long-term gains)
    "w40k": (40000, 0, 0),
    "w100k": (100000, 0, 0),
    "w250k": (250000, 0, 0),
    "mixed": (80000, 5000, 10000),
}
CALC = LocalCalculator()


def run(region, scenario, state_base="0", **kw):
    wages, dividends, ltcg = (D(v) for v in SCENARIOS[scenario])
    agi = wages + dividends + ltcg
    values = dict(
        jurisdiction_id=region, tax_year=2026, filing_status="single", is_resident=True,
        total_income=agi, wages=wages, state_taxable_income=D(state_base),
        dividends=dividends, qualified_dividends=dividends, net_short_term_gains=D(0),
        net_long_term_gains=ltcg, state_agi=agi, taxpayer_age_at_year_end=40,
        baseline_profile_supported=True,
    )
    values.update(kw)
    tax_input = LocalTaxInput(**values)
    rules = CALC.loader.load_local_rules(region, 2026)
    result = LOCAL_POLICIES_2026[region](tax_input, rules, CALC)
    assert result.net_tax == result.total_tax
    assert sum((c.tax for c in result.tax_components), D(0)) == result.tax_before_credits
    assert result.total_tax == (
        result.tax_before_credits - result.nonrefundable_credits - result.refundable_credits
    )
    return result


def test_registry_covers_advertised_cities_without_overlap():
    assert set(LOCAL_POLICIES_2026) | set(LOCAL_PENDING_2026) == ADVERTISED
    assert not set(LOCAL_POLICIES_2026) & set(LOCAL_PENDING_2026)
    for region in LOCAL_PENDING_2026:
        assert region not in LOCAL_POLICIES_2026


# NYC (IT-2105-I 2026; Tax Law 11-1701): base = NY taxable income = FAGI - 8,000.
# Tax: 3.078% to 12,000; 369 + 3.762% to 25,000; 858 + 3.819% to 50,000;
# 1,813 + 3.876% above (published whole-dollar base amounts). Refundable school
# credits: fixed 63 (FAGI <= 250,000); rate reduction 21 + 0.228% x (taxable - 12,000)
# (FAGI <= 500,000).
@pytest.mark.parametrize("scenario,base,gross,credits,expected", [
    # 858 + 7,000 x .03819 = 1,125.33; 63 + 21 + 20,000 x .00228 = 129.60
    ("w40k", "32000", "1125.33", "129.60", "995.73"),
    # 1,813 + 42,000 x .03876 = 3,440.92; 63 + 21 + 182.40 = 266.40
    ("w100k", "92000", "3440.92", "266.40", "3174.52"),
    # 1,813 + 192,000 x .03876 = 9,254.92; 63 + 21 + 524.40 = 608.40
    ("w250k", "242000", "9254.92", "608.40", "8646.52"),
    # 1,813 + 37,000 x .03876 = 3,247.12; 63 + 21 + 171 = 255
    ("mixed", "87000", "3247.12", "255.00", "2992.12"),
])
def test_nyc(scenario, base, gross, credits, expected):
    result = run("US-NY-NYC", scenario, base)
    assert result.tax_before_credits == D(gross)
    assert result.refundable_credits == D(credits)
    assert result.total_tax == D(expected)


def test_nyc_school_fixed_credit_stops_above_250000():
    data = run("US-NY-NYC", "w250k", "242000", total_income=D("250001"))
    amounts = {c.credit_id: c.amount_applied for c in data.credits}
    assert amounts["NYC-SCHOOL-FIXED"] == D(0)


