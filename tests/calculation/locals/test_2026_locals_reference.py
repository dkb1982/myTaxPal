def test_unsupported_profile_and_year_are_rejected():
    with pytest.raises(ValueError):
        run("US-OH-CLE", "w40k", num_dependents=1)
    rules = CALC.loader.load_local_rules("US-OH-CLE", 2026)
    data = LocalTaxInput(
        jurisdiction_id="US-OH-CLE", tax_year=2025, filing_status="single", is_resident=True,
        total_income=D(1), wages=D(1), dividends=D(0), qualified_dividends=D(0),
        net_short_term_gains=D(0), net_long_term_gains=D(0), taxpayer_age_at_year_end=40,
        baseline_profile_supported=True,
    )
    with pytest.raises(ValueError):
        LOCAL_POLICIES_2026["US-OH-CLE"](data, rules, CALC)
