def test_baltimore_poverty_credit_inclusive_2026_guideline():
    # 10-709: FAGI and earned income not exceeding $15,960; credit = 3.2% x wages
    # capped at county tax. 15,960 - 3,400 - 3,200 = 9,360 x .032 = 299.52.
    data = dict(total_income=D(15960), wages=D(15960), state_agi=D(15960),
                federal_earned_income_credit=D(0))
    result = run("US-MD-BAL", "w40k", "9360", **data)
    assert result.tax_before_credits == D("299.52")
    assert result.total_tax == D(0)
    data.update(total_income=D(15961), wages=D(15961), state_agi=D(15961))
    assert run("US-MD-BAL", "w40k", "9361", **data).total_tax == D("299.55")


def test_baltimore_local_eic_is_ten_times_rate_of_federal_eic():
    # 18,000 FAGI: MD taxable 11,400 x .032 = 364.80; EIC 100 x 10 x .032 = 32.
    result = run("US-MD-BAL", "w40k", "11400", total_income=D(18000), wages=D(18000),
                 state_agi=D(18000), federal_earned_income_credit=D(100))
