def test_self_employment_refused_for_2026():
    with pytest.raises(UnsupportedIncomeError):
        _calc(IncomeBreakdown(employment_wages=D("50000"), self_employment=D("10000")))


def test_period_label_and_quebec_still_refused():
    r = _calc(gross="60000")
    assert any("Calendar 2026" in n and "14%" in n for n in r.calculation_notes)
    with pytest.raises(ValueError, match="Quebec"):
        _calc(gross="80000", province="QC")


