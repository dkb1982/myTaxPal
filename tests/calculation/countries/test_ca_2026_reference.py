D = Decimal
TOL = D("0.05")


def _calc(breakdown: IncomeBreakdown | None = None, gross: str | None = None, **profile):
    if breakdown is None:
        breakdown = IncomeBreakdown(employment_wages=D(gross))
    tax_input = InternationalTaxInput(
        country_code="CA",
        tax_year=2026,
        gross_income=breakdown.total,
        income_breakdown=breakdown,
        ca=CATaxInput(**profile) if profile else None,
    )
    return CACalculator().calculate(tax_input)


def test_40k_ontario():
    # CPP: 36,500 x 4.95% = 1,806.75 base + 365.00 enhanced = 2,171.75 ; EI 40,000 x 1.63% = 652.00
    # Net income = 40,000 - 365 = 39,635
    # Federal: 39,635 x 14% = 5,548.90 - (16,452 + 1,501 + 1,806.75 + 652) x 14% (2,857.645)
    #          = 2,691.26
    # Ontario: 39,635 x 5.05% = 2,001.5675 - (12,989 + 1,806.75 + 652) x 5.05% (780.1114)
    #          = 1,221.46 ; surtax 0 ; reduction max(0, 600 - 1,221.46) = 0
    #          LIFT = 875 - (39,635 - 32,500) x 5% = 518.25 -> ON tax 703.21
    # OHP (38,500-48,000) = 450
    # Total = 2,691.26 + 703.21 + 450 + 2,171.75 + 652 = 6,668.22
    r = _calc(gross="40000")
    assert r.social_insurance == D("2823.75")
    assert abs(r.income_tax - D("3394.47")) <= TOL
    assert r.other_taxes == D("450.00")
    assert abs(r.total_tax - D("6668.22")) <= TOL
    assert r.tax_year == 2026


